"use client";

import * as Tabs from "@radix-ui/react-tabs";
import { Check, Copy } from "lucide-react";
import { useEffect, useRef, useState } from "react";

export type CodeTabItem = {
  language: string;
  label: string;
  code: string;
  /** Pre-highlighted HTML from the server. When absent, plain text is rendered. */
  html?: string;
};

export function CodeTabs({ items, title }: { items: CodeTabItem[]; title?: string }) {
  const [active, setActive] = useState(items[0]?.label ?? "");
  const [copied, setCopied] = useState(false);
  const timer = useRef<ReturnType<typeof setTimeout> | null>(null);
  const current = items.find((i) => i.label === active) ?? items[0];

  useEffect(() => () => void (timer.current && clearTimeout(timer.current)), []);

  async function copy() {
    if (!current) return;
    try {
      await navigator.clipboard.writeText(current.code);
      setCopied(true);
      if (timer.current) clearTimeout(timer.current);
      timer.current = setTimeout(() => setCopied(false), 2000);
    } catch {
      setCopied(false);
    }
  }

  return (
    <figure className="overflow-hidden rounded-lg border border-border bg-surface">
      <Tabs.Root value={current?.label} onValueChange={setActive}>
        <div className="flex items-center justify-between gap-2 border-b border-border bg-surface-raised/50 pr-2">
          {items.length > 1 ? (
            <Tabs.List aria-label={title ? `${title} language` : "Language"} className="flex min-w-0 overflow-x-auto">
              {items.map((i) => (
                <Tabs.Trigger
                  key={i.label}
                  value={i.label}
                  className="min-h-11 whitespace-nowrap border-b-2 border-transparent px-4 text-sm text-fg-muted hover:text-fg data-[state=active]:border-cyan data-[state=active]:text-fg"
                >
                  {i.label}
                </Tabs.Trigger>
              ))}
            </Tabs.List>
          ) : (
            <span className="px-4 py-3 text-sm text-fg-muted">{title ?? current?.label}</span>
          )}
          <button
            type="button"
            onClick={copy}
            className="inline-flex min-h-11 shrink-0 items-center gap-2 rounded-md px-3 text-sm text-fg-muted hover:bg-surface hover:text-fg"
          >
            {copied ? <Check aria-hidden className="size-4 text-success" /> : <Copy aria-hidden className="size-4" />}
            Copy
            <span role="status" aria-live="polite" className="sr-only">
              {copied ? "Copied" : ""}
            </span>
          </button>
        </div>
        {items.map((i) => (
          <Tabs.Content key={i.label} value={i.label} className="focus-visible:outline-offset-[-2px]">
            {i.html ? (
              <div
                className="overflow-x-auto p-4 font-mono text-sm leading-relaxed [&_pre]:!bg-transparent [&_pre]:m-0"
                // Trusted: generated by shiki on the server from our own source strings.
                dangerouslySetInnerHTML={{ __html: i.html }}
              />
            ) : (
              <pre className="overflow-x-auto p-4 font-mono text-sm leading-relaxed text-fg">
                <code>{i.code}</code>
              </pre>
            )}
          </Tabs.Content>
        ))}
      </Tabs.Root>
      {title && items.length > 1 && <figcaption className="sr-only">{title}</figcaption>}
    </figure>
  );
}
